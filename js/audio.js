/* ==========================================================================
   audio.js
   Sound effects created with the Web Audio API.
   No sound files are needed: every sound is generated by an oscillator
   (a tone) or by random noise (explosions).

   Browsers only allow audio after the user interacts with the page, so
   KB.audio.resume() is called on the first click / key press.
   ========================================================================== */

KB.audio = {
  ctx: null,
  master: null,
  muted: false,

  /** Create the audio context (once). */
  init() {
    if (this.ctx) return;
    try {
      const AC = window.AudioContext || window.webkitAudioContext;
      this.ctx = new AC();
      this.master = this.ctx.createGain();
      this.master.gain.value = 0.25;           // overall volume
      this.master.connect(this.ctx.destination);
    } catch (e) {
      this.ctx = null;                          // audio not supported: stay silent
    }
  },

  /** Call from a user gesture. Starts / un-suspends the audio engine. */
  resume() {
    this.init();
    if (this.ctx && this.ctx.state === 'suspended') this.ctx.resume();
  },

  /**
   * Play one tone.
   * @param freq  start frequency in Hz
   * @param dur   duration in seconds
   * @param type  'sine' | 'square' | 'sawtooth' | 'triangle'
   * @param vol   volume 0..1
   * @param slide how many Hz to glide by during the sound (can be negative)
   */
  tone(freq, dur, type = 'square', vol = 0.3, slide = 0) {
    if (!this.ctx || this.muted) return;
    const t = this.ctx.currentTime;
    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();
    osc.type = type;
    osc.frequency.setValueAtTime(freq, t);
    if (slide) osc.frequency.exponentialRampToValueAtTime(Math.max(30, freq + slide), t + dur);
    // fade out quickly so the sound does not "click"
    gain.gain.setValueAtTime(vol, t);
    gain.gain.exponentialRampToValueAtTime(0.001, t + dur);
    osc.connect(gain);
    gain.connect(this.master);
    osc.start(t);
    osc.stop(t + dur + 0.02);
  },

  /** Short burst of white noise: used for explosions. */
  noise(dur = 0.3, vol = 0.4) {
    if (!this.ctx || this.muted) return;
    const t = this.ctx.currentTime;
    const len = Math.floor(this.ctx.sampleRate * dur);
    const buf = this.ctx.createBuffer(1, len, this.ctx.sampleRate);
    const data = buf.getChannelData(0);
    for (let i = 0; i < len; i++) data[i] = (Math.random() * 2 - 1) * (1 - i / len);
    const src = this.ctx.createBufferSource();
    const gain = this.ctx.createGain();
    src.buffer = buf;
    gain.gain.value = vol;
    src.connect(gain);
    gain.connect(this.master);
    src.start(t);
  },

  // ---- Named sound effects used by the game ----

  /** Correct key. The pitch rises with the combo so streaks sound exciting. */
  key(combo = 0) { this.tone(520 + Math.min(combo, 30) * 12, 0.05, 'square', 0.12); },
  /** Wrong key. */
  wrong() { this.tone(140, 0.16, 'sawtooth', 0.25, -60); },
  /** A whole word / drill completed. */
  word() { this.tone(784, 0.08, 'triangle', 0.3); setTimeout(() => this.tone(1047, 0.12, 'triangle', 0.3), 70); },
  /** Explosion. */
  boom() { this.noise(0.35, 0.4); this.tone(90, 0.3, 'sawtooth', 0.25, -50); },
  /** Combo milestone (every 10 correct keys in a row). */
  combo() { [660, 880, 1175].forEach((f, i) => setTimeout(() => this.tone(f, 0.09, 'square', 0.18), i * 60)); },
  /** Countdown beep. */
  count() { this.tone(440, 0.12, 'sine', 0.3); },
  /** Countdown "GO!" */
  go() { this.tone(880, 0.3, 'sine', 0.3); },
  /** Victory jingle. */
  win() { [523, 659, 784, 1047].forEach((f, i) => setTimeout(() => this.tone(f, 0.18, 'triangle', 0.3), i * 120)); },
  /** Defeat sound. */
  lose() { [392, 330, 262].forEach((f, i) => setTimeout(() => this.tone(f, 0.25, 'sawtooth', 0.22), i * 160)); }
};
